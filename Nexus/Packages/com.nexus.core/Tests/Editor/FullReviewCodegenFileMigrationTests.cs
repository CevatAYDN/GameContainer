#if !UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using Nexus.Editor;

namespace Nexus.Editor.Tests
{
    // Host uses isolated settings/AssetDatabase stubs, but the real generator and filesystem.
    public sealed class FullReviewCodegenFileMigrationTests
    {
        public void CuratedDestination_PreservesTheOldBinderAndMetaOnRefusal()
        {
            InFixture((oldBinder, oldMeta, output) =>
            {
                File.WriteAllText(oldBinder, "// <auto-generated> old binder");
                File.WriteAllText(oldMeta, "old-meta");
                File.WriteAllText(Path.Combine(output, "link.xml"), "<linker><!-- curated --></linker>");
                Exception refusal = null;
                try { NexusCodeGenerator.GenerateBinder(); }
                catch (InvalidOperationException ex) { refusal = ex; }
                Require(refusal != null && refusal.Message.Contains("Overwrite blocked"), "must actually reach ownership preflight");
                Require(File.Exists(oldBinder) && File.ReadAllText(oldBinder) == "// <auto-generated> old binder"
                    && File.Exists(oldMeta) && File.ReadAllText(oldMeta) == "old-meta",
                    "refused migration must not delete the previous binder or its GUID");
            });
        }

        public void CuratedDefaultBinder_IsNotDeletedDuringMigration()
        {
            InFixture((oldBinder, oldMeta, output) =>
            {
                File.WriteAllText(oldBinder, "// hand-maintained binder");
                File.WriteAllText(oldMeta, "owned-meta");
                bool refused = false;
                try { NexusCodeGenerator.GenerateBinder(); }
                catch (InvalidOperationException ex) { refused = ex.Message.Contains("Overwrite blocked"); }
                Require(refused && File.Exists(oldBinder) && File.ReadAllText(oldBinder) == "// hand-maintained binder"
                    && File.Exists(oldMeta) && File.ReadAllText(oldMeta) == "owned-meta",
                    "a default-path file without the ownership tag must remain untouched");
            });
        }

        public void SuccessfulMigration_RemovesOldGeneratedFilesOnlyAfterNewOutputsExist()
        {
            InFixture((oldBinder, oldMeta, output) =>
            {
                File.WriteAllText(oldBinder, "// <auto-generated> old binder");
                File.WriteAllText(oldMeta, "old-meta");
                NexusCodeGenerator.GenerateBinder();
                Require(!File.Exists(oldBinder) && !File.Exists(oldMeta), "successful migration must retire the old generated script and GUID");
                Require(File.ReadAllText(Path.Combine(output, "NexusGeneratedBinder.g.cs")).Contains("<auto-generated>")
                    && File.ReadAllText(Path.Combine(output, "link.xml")).Contains("<auto-generated>")
                    && NexusCodeGenerator.IsBinderCurrent(), "both replacements must exist and match current generation");
            });
        }

        private static void InFixture(Action<string, string, string> test)
        {
            string root = Path.Combine(NexusBench.Program.TempRoot, "binder-migration-" + Guid.NewGuid().ToString("N"));
            string output = NexusEditorSettings.OutputRoot;
            string previousDirectory = Environment.CurrentDirectory;
            var backup = new Dictionary<string, byte[]>();
            Directory.CreateDirectory(output);
            foreach (string name in new[] { "NexusGeneratedBinder.g.cs", "link.xml", ".gitignore" })
            {
                string path = Path.Combine(output, name);
                backup[path] = File.Exists(path) ? File.ReadAllBytes(path) : null;
                if (File.Exists(path)) File.Delete(path);
            }
            Directory.CreateDirectory(Path.Combine(root, "Assets/Scripts/Nexus"));
            try
            {
                Environment.CurrentDirectory = root;
                string binder = Path.Combine(root, "Assets/Scripts/Nexus/NexusGeneratedBinder.g.cs");
                test(binder, binder + ".meta", output);
            }
            finally
            {
                Environment.CurrentDirectory = previousDirectory;
                foreach (var file in backup)
                {
                    if (file.Value != null) File.WriteAllBytes(file.Key, file.Value);
                    else if (File.Exists(file.Key)) File.Delete(file.Key);
                }
                string absolute = Path.GetFullPath(root);
                Require(absolute.StartsWith(Path.GetFullPath(NexusBench.Program.TempRoot) + Path.DirectorySeparatorChar,
                    StringComparison.OrdinalIgnoreCase) && Path.GetFileName(absolute).StartsWith("binder-migration-", StringComparison.Ordinal),
                    "fixture cleanup must stay under its own temporary root");
                if (Directory.Exists(absolute)) Directory.Delete(absolute, true);
            }
        }

        private static void Require(bool condition, string message)
        {
            if (!condition) throw new InvalidOperationException(message);
        }
    }
}
#endif
