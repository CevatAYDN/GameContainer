using System;
using System.IO;
using System.Text.RegularExpressions;
using NUnit.Framework;
using UnityEditor;
using UnityEditor.Compilation;
using UnityEngine;
using UnityEngine.TestTools;

namespace Nexus.Editor.Tests
{
    /// <summary>
    /// The binder self-heal counted every heal of an editor session, so after three removed or renamed injectable types that
    /// each healed, the fourth was refused, the project kept its compile errors and the message blamed the generator (#244).
    /// Only heals in a row, whose regenerated binder failed again, count.
    /// </summary>
    public sealed class BinderSelfHealTests
    {
        private string _dir;
        private string _binder;

        [SetUp]
        public void SetUp()
        {
            _dir = Path.Combine(Path.GetTempPath(), "nexus-selfheal-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(_dir);
            _binder = Path.Combine(_dir, "NexusGeneratedBinder.g.cs");
            SessionState.EraseInt(NexusBinderSelfHeal.HealCountKey);
            SessionState.EraseBool(NexusBinderSelfHeal.RegenerateKey);
        }

        [TearDown]
        public void TearDown()
        {
            // a regenerate request left set would rewrite the project's binder at the next domain reload
            SessionState.EraseInt(NexusBinderSelfHeal.HealCountKey);
            SessionState.EraseBool(NexusBinderSelfHeal.RegenerateKey);
            Directory.Delete(_dir, true);
        }

        /// <summary>A compilation that failed inside the binder; true when the heal emptied it.</summary>
        private bool Heal()
        {
            File.WriteAllText(_binder, "// <auto-generated> names a removed type </auto-generated>\n");
            NexusBinderSelfHeal.OnAssemblyCompiled("Assembly-CSharp", new[]
            {
                new CompilerMessage { type = CompilerMessageType.Error, file = _binder, message = "error CS0246: The type or namespace name 'Removed' could not be found" }
            });
            // the regeneration the heal asks for is not run here: it would rewrite the project's binder
            SessionState.EraseBool(NexusBinderSelfHeal.RegenerateKey);
            return File.ReadAllText(_binder) == NexusBinderSelfHeal.Placeholder;
        }

        [Test]
        public void OnlyHealsInARowCount_ABinderThatCompiledLetsTheNextOneHeal()
        {
            for (int i = 0; i < 3; i++) Assert.IsTrue(Heal(), "heal " + (i + 1));
            LogAssert.Expect(LogType.Error, new Regex(@"failed to compile after each of 3 regenerations in a row"));
            Assert.IsFalse(Heal(), "a fourth heal in a row is refused: the generator keeps writing a broken binder");

            NexusBinderSelfHeal.OnDomainReloaded(compilationFailed: false); // the regenerated binder compiled
            Assert.IsTrue(Heal(), "a binder that compiled resets the count, so a later removed type heals");
        }
    }
}
