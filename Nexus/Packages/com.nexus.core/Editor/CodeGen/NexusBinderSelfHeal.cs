using System;
using System.IO;
using UnityEditor;
using UnityEditor.Compilation;
using UnityEngine;

namespace Nexus.Editor
{
    /// <summary>
    /// The generated binder names every injectable type, so deleting or renaming one makes the binder itself fail to compile, and a
    /// project that does not compile cannot run the generator that would fix it. When a compilation fails with errors inside
    /// NexusGeneratedBinder.g.cs, the stale file is emptied (it is generated; the code is the source of truth; an empty file keeps its
    /// .meta and GUID), the project compiles without it (injection falls back to reflection) and the binder is generated again after
    /// that compilation. Batchmode stops on the first failed compilation unless Unity is started with -ignorecompilererrors;
    /// with it, this healing runs and <see cref="NexusCodeGenerator.GenerateBinder"/> ends with a binder written from the
    /// current code (issue #77, TROUBLESHOOTING.md "Stale Generated Binder").
    /// </summary>
    [InitializeOnLoad]
    internal static class NexusBinderSelfHeal
    {
        private const string BinderFile = "NexusGeneratedBinder.g.cs";
        private const string RegenerateKey = "Nexus.BinderSelfHeal.Regenerate";
        private const string HealCountKey = "Nexus.BinderSelfHeal.Count";
        /// <summary>Heals per editor session; a generator that keeps producing a broken binder must not loop forever.</summary>
        private const int MaxHeals = 3;

        static NexusBinderSelfHeal()
        {
            CompilationPipeline.assemblyCompilationFinished -= OnAssemblyCompiled;
            CompilationPipeline.assemblyCompilationFinished += OnAssemblyCompiled;
            if (SessionState.GetBool(RegenerateKey, false) && !EditorUtility.scriptCompilationFailed)
            {
                SessionState.SetBool(RegenerateKey, false);
                EditorApplication.delayCall += () =>
                {
                    Debug.Log("[Nexus] Regenerating the AOT binder removed after a failed compilation.");
                    NexusCodeGenerator.GenerateBinder();
                };
            }
        }

        private static void OnAssemblyCompiled(string assembly, CompilerMessage[] messages)
        {
            string stale = null;
            foreach (var message in messages)
            {
                if (message.type != CompilerMessageType.Error || string.IsNullOrEmpty(message.file)) continue;
                if (message.file.Replace('\\', '/').EndsWith("/" + BinderFile, StringComparison.OrdinalIgnoreCase)) { stale = message.file; break; }
            }
            if (stale == null) return;
            int heals = SessionState.GetInt(HealCountKey, 0);
            if (heals >= MaxHeals)
            {
                Debug.LogError($"[Nexus] The generated binder still fails to compile after {MaxHeals} regenerations; fix the generator output or delete {stale} by hand.");
                return;
            }
            SessionState.SetInt(HealCountKey, heals + 1);
            SessionState.SetBool(RegenerateKey, true);
            Debug.LogWarning($"[Nexus] {stale} names a type that no longer compiles (removed or renamed). Emptying the generated binder; it is regenerated after the next successful compilation.");
            // Asset operations are not allowed while compiling: rewrite on disk now, let the asset database notice on the next editor tick.
            try { File.WriteAllText(stale, Placeholder); }
            catch (IOException ex) { Debug.LogWarning($"[Nexus] Could not empty {stale}: {ex.Message}"); return; }
            catch (UnauthorizedAccessException ex) { Debug.LogWarning($"[Nexus] Could not empty {stale}: {ex.Message}"); return; }
            EditorApplication.delayCall += AssetDatabase.Refresh;
        }

        /// <summary>Keeps the generator's ownership tag, or <see cref="NexusCodeGenerator.GenerateBinder"/> refuses to overwrite the file.</summary>
        internal const string Placeholder = "// <auto-generated> Emptied after a failed compilation. Nexus > Generate AOT Binder writes the binder again. </auto-generated>\n";
    }
}
