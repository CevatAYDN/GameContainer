    /// <summary>Generates the <c>AdPlacements</c> constants from the settings' placement names, so a misspelt name does not compile.</summary>
    public static class AdPlacementsGenerator
    {
        private static readonly Regex Identifier = new Regex("^[A-Za-z_][A-Za-z0-9_]*$");

        public static string Render(IEnumerable<PlacementEntry> placements)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated> Nexus Ads > Generate Placements; edit the placements in Project Settings > Nexus Ads, not this file. </auto-generated>\n");
            sb.Append("namespace Nexus.Ads\n{\n    /// <summary>The placement names declared in the ads settings; game code names a placement only through these.</summary>\n    public static class AdPlacements\n    {\n");
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var p in placements)
            {
                if (!Identifier.IsMatch(p.Name ?? "")) throw new InvalidOperationException("placement '" + p.Name + "' is not a C# identifier");
                if (!seen.Add(p.Name)) throw new InvalidOperationException("placement '" + p.Name + "' is declared twice");
                sb.Append("        /// <summary>").Append(p.Format).Append(p.NaturalBreak ? ", natural break" : "").Append("</summary>\n");
                sb.Append("        public const string ").Append(Pascal(p.Name)).Append(" = \"").Append(p.Name).Append("\";\n");
            }
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        /// <summary>shop_refill → ShopRefill; already-Pascal names stay.</summary>
        public static string Pascal(string name)
        {
            var sb = new StringBuilder();
            bool upper = true;
            foreach (char c in name)
            {
                if (c == '_') { upper = true; continue; }
                sb.Append(upper ? char.ToUpperInvariant(c) : c);
                upper = false;
            }
            return sb.ToString();
        }

        public static string Write(AdsSettings settings)
        {
            string path = string.IsNullOrWhiteSpace(settings.GeneratedPlacementsPath) ? "Assets/Scripts/Ads/AdPlacements.g.cs" : settings.GeneratedPlacementsPath;
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path)));
            File.WriteAllText(path, Render(settings.Placements).Replace("\n", "\r\n"));
            AssetDatabase.ImportAsset(path);
            return path;
        }
    }

    /// <summary>Joins the per-network app-ads.txt lines into one file; the publisher uploads it to the developer website named in the store listing.</summary>
    public static class AppAdsTxt
    {
        public static string Render(IEnumerable<string> lines)
        {
            var sb = new StringBuilder();
            sb.Append("# app-ads.txt generated by Nexus Ads; one line per network as its dashboard gives it\n");
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var raw in lines)
            {
                string line = (raw ?? "").Trim();
                if (line.Length == 0 || !seen.Add(line)) continue;
                sb.Append(line).Append('\n');
            }
            return sb.ToString();
        }

        /// <summary>The first field of an app-ads.txt record (the ad system domain), trimmed; empty for a comment, a variable or a blank line.</summary>
        public static string AdSystemDomain(string line)
        {
            string record = line ?? "";
            int comment = record.IndexOf('#');
            if (comment >= 0) record = record.Substring(0, comment);
            int comma = record.IndexOf(',');
            return comma < 0 ? "" : record.Substring(0, comma).Trim();
        }
    }

    /// <summary>
    /// Keeps every com.nexus.ads* git-URL entry of a consumer's Packages/manifest.json at one commit:
    /// the commit of com.nexus.ads. Embedded or file: entries are left alone.
    /// </summary>
    public static class ManifestPinning
    {
        private static readonly Regex Entry = new Regex("\"(com\\.nexus\\.ads[a-z.]*)\"\\s*:\\s*\"([^\"]*GameContainer\\.git\\?path=[^\"#]*#)([0-9a-f]{7,40})\"", RegexOptions.IgnoreCase);

        /// <summary>The git-pinned family entries: name → commit.</summary>
        public static Dictionary<string, string> Pins(string manifestJson)
        {
            var pins = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (Match m in Entry.Matches(manifestJson ?? "")) pins[m.Groups[1].Value] = m.Groups[3].Value;
            return pins;
        }

        /// <summary>Null when every pinned family entry carries the same commit; otherwise the fault sentence.</summary>
        public static string Fault(string manifestJson)
        {
            var pins = Pins(manifestJson);
            if (pins.Count < 2) return null;
            string first = null, firstName = null;
            foreach (var pair in pins)
            {
                if (first == null) { first = pair.Value; firstName = pair.Key; continue; }
                if (!string.Equals(first, pair.Value, StringComparison.OrdinalIgnoreCase))
                    return firstName + " is pinned at " + first + " but " + pair.Key + " at " + pair.Value + "; the family packages must share one commit.";
            }
            return null;
        }

        /// <summary>Rewrites every pinned family entry to the commit of com.nexus.ads (or the given one). Returns the manifest unchanged when nothing is pinned.</summary>
        public static string Pin(string manifestJson, string commit = null)
        {
            var pins = Pins(manifestJson);
            if (pins.Count == 0) return manifestJson;
            commit = commit ?? (pins.TryGetValue("com.nexus.ads", out var core) ? core : null);
            if (commit == null) return manifestJson;
            return Entry.Replace(manifestJson, m => "\"" + m.Groups[1].Value + "\": \"" + m.Groups[2].Value + commit + "\"");
        }
    }

    /// <summary>The link.xml that keeps the family's reflection-reached types through IL2CPP stripping; written to its own folder, away from the core binder's.</summary>
    public static class LinkXml
    {
        public const string DefaultPath = "Assets/NexusAds/link.xml";

        public static string Render(AdProviderKind kind)
        {
            var sb = new StringBuilder("<linker>\n  <assembly fullname=\"Nexus.Ads.Core\" preserve=\"all\"/>\n  <assembly fullname=\"Nexus.Ads.Unity\" preserve=\"all\"/>\n");
            if (kind != AdProviderKind.None) sb.Append("  <assembly fullname=\"Nexus.Ads.").Append(kind).Append("\" preserve=\"all\"/>\n");
            sb.Append("</linker>\n");
            return sb.ToString();
        }

        public static string Write(AdProviderKind kind, string path = DefaultPath)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path)));
            File.WriteAllText(path, Render(kind).Replace("\n", "\r\n"));
            AssetDatabase.ImportAsset(path);
            return path;
        }
    }
